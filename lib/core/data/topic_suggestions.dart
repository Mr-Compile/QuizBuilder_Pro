  /// Search topics by query string
  static List<String> searchTopics(String query) {
    if (query.isEmpty) return allTopics;
    
    final lowerQuery = query.toLowerCase();
    return allTopics.where((topic) 
      => topic.toLowerCase().contains(lowerQuery)
    ).toList();
  }

  /// Get topics for a specific category
  static List<String> getTopicsByCategory(String category) {
    return topicsByCategory[category] ?? [];
  }

  /// Get all category names
  static List<String> get categories => topicsByCategory.keys.toList();

  /// Check if a topic exists in suggestions
  static bool containsTopic(String topic) {
    return allTopics.map((t) => t.toLowerCase()).contains(topic.toLowerCase());
  }

